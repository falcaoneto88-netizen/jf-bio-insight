CREATE TABLE public.patients (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL CHECK (char_length(btrim(name)) BETWEEN 2 AND 150),
  email text NOT NULL DEFAULT '' CHECK (char_length(email) <= 254),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.consultations (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  patient_id uuid NOT NULL REFERENCES public.patients(id),
  patient_name text NOT NULL CHECK (char_length(btrim(patient_name)) BETWEEN 2 AND 150),
  consultation_date date NOT NULL,
  invite_email text NOT NULL DEFAULT '' CHECK (invite_email = lower(btrim(invite_email)) AND char_length(invite_email) <= 254),
  invite_expires_at timestamptz NOT NULL DEFAULT now() + interval '14 days',
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX consultations_patient_idx ON public.consultations(patient_id, consultation_date DESC);

-- Narrow identity check: only the current user's verified email is returned.
-- No clinical data is read and no service-role client is used.
CREATE FUNCTION public.current_verified_email() RETURNS text
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
  SELECT lower(u.email) FROM auth.users u
  WHERE u.id = (SELECT auth.uid()) AND u.email_confirmed_at IS NOT NULL;
$$;
REVOKE ALL ON FUNCTION public.current_verified_email() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.current_verified_email() TO authenticated;

