-- One transaction creates the patient, consultation and draft. Retries use the
-- same IDs. SECURITY INVOKER retains the authenticated user's grants and RLS.
CREATE FUNCTION public.create_patient_consultation(
  _id uuid, _patient_id uuid, _name text, _email text,
  _date date, _existing_patient boolean
) RETURNS uuid LANGUAGE plpgsql SECURITY INVOKER SET search_path = '' AS $$
DECLARE
  patient public.patients%ROWTYPE;
  consultation public.consultations%ROWTYPE;
  normalized_email text := lower(btrim(_email));
BEGIN
  IF NOT public.has_role((SELECT auth.uid()), 'admin') THEN
    RAISE EXCEPTION 'Acesso restrito a administradores.' USING ERRCODE = '42501';
  END IF;
  IF NOT _existing_patient THEN
    INSERT INTO public.patients(id, name, email)
      VALUES (_patient_id, btrim(_name), normalized_email) ON CONFLICT (id) DO NOTHING;
  END IF;
  SELECT * INTO patient FROM public.patients WHERE id = _patient_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Paciente indisponível.' USING ERRCODE = '23503';
  END IF;
  IF NOT _existing_patient AND (patient.name <> btrim(_name) OR patient.email <> normalized_email) THEN
    RAISE EXCEPTION 'O cadastro foi alterado. Reabra a consulta.' USING ERRCODE = '23505';
  END IF;
  INSERT INTO public.consultations(id, patient_id, patient_name, consultation_date, invite_email)
    VALUES (_id, _patient_id, patient.name, _date, normalized_email) ON CONFLICT (id) DO NOTHING;
  SELECT * INTO consultation FROM public.consultations WHERE id = _id;
  IF consultation.patient_id <> _patient_id OR consultation.consultation_date <> _date
    OR consultation.invite_email <> normalized_email THEN
    RAISE EXCEPTION 'A consulta já foi criada com outros dados.' USING ERRCODE = '23505';
  END IF;
  INSERT INTO public.consultation_drafts(consultation_id) VALUES (_id)
    ON CONFLICT (consultation_id) DO NOTHING;
  RETURN _id;
END;
$$;
REVOKE ALL ON FUNCTION public.create_patient_consultation(uuid, uuid, text, text, date, boolean) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.create_patient_consultation(uuid, uuid, text, text, date, boolean) TO authenticated;
COMMIT;
