/** Datas clínicas são datas civis; nunca converter com timezone do navegador. */
export function documentDate(value: string, locale: ProtocolLocale): string {
  const br = toBrDate(value);
  if (locale !== "en") return br;
  return br.replace(/^(\d{2})\/(\d{2})\/(\d{4})/, "$2/$1/$3");
}
